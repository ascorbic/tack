/** The emoji a shortcode stands for (`:pray:` → 🙏), or null if it isn't one we know. */
export function emojiFromShortcode(shortcode: string | null | undefined): string | null {
	const name = /^:([\w+-]+):$/.exec(shortcode?.trim() ?? "")?.[1];
	return name ? (SHORTCODES[name.toLowerCase()] ?? null) : null;
}

/** The emoji in GraphQL's `emojiHTML` (`<div><g-emoji …>🙏</g-emoji></div>`), or null. */
export function emojiFromHtml(html: string | null | undefined): string | null {
	const text = (html ?? "")
		.replace(/<[^>]*>/g, "")
		.replace(/&#x([0-9a-f]+);/gi, (_, hex: string) =>
			String.fromCodePoint(Number.parseInt(hex, 16)),
		)
		.replace(/&#(\d+);/g, (_, dec: string) => String.fromCodePoint(Number(dec)))
		.trim();
	// One emoji is a short run of characters at most (flags, families, skin tones).
	return text && text.length <= 16 && !/[<>&\w]/.test(text) ? text : null;
}

/** A category's emoji, from whatever GitHub said: its HTML first, then its shortcode. */
export function categoryEmoji(html?: string | null, shortcode?: string | null): string | null {
	return emojiFromHtml(html) ?? emojiFromShortcode(shortcode);
}
